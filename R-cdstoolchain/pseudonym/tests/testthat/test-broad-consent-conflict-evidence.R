test_that("conflicting frontend history writes local evidence without leaking identifiers", {
  connection <- getOption("interpolar.test.postgres_connection")
  skip_if(is.null(connection), "An isolated PostgreSQL test connection was not supplied.")
  schema <- basename(tempfile("bc_conflict_"))
  snapshotEnsureSchema(connection, schema)
  on.exit(DBI::dbExecute(connection, paste0("DROP SCHEMA ", DBI::dbQuoteIdentifier(connection, schema), " CASCADE")), add = TRUE)
  tables <- writeBroadConsentSnapshotFixture(connection, schema)
  cases <- tables$fall_fe[c(1, 2, 1), ]
  cases$fall_fe_id <- 777L
  cases$record_id <- c("PRIVATE-R1", "PRIVATE-R2", "PRIVATE-R1")
  cases$fall_pat_id <- c("PRIVATE-P1", "PRIVATE-P2", "PRIVATE-WRONG")
  cases$input_datetime <- as.POSIXct("2026-10-22 10:00:00", tz = "UTC") + 1:3
  cases$input_processing_nr <- 101:103
  DBI::dbExecute(connection, paste0("ALTER TABLE ", schema, ".fall_fe ADD COLUMN input_datetime timestamp, ADD COLUMN input_processing_nr integer"))
  DBI::dbExecute(connection, paste0("TRUNCATE ", schema, ".fall_fe"))
  DBI::dbAppendTable(connection, DBI::Id(schema = schema, table = "fall_fe"), cases)
  DBI::dbExecute(connection, paste0("CREATE OR REPLACE VIEW ", schema, ".v_fall_fe AS SELECT * FROM ", schema, ".fall_fe"))
  DBI::dbExecute(connection, paste0("UPDATE ", schema, ".patient_fe SET record_id = 'PRIVATE-R' || patient_fe_id, pat_id = 'PRIVATE-P' || patient_fe_id"))
  intervals <- basename(tempfile("bc_intervals_"))
  DBI::dbWriteTable(connection, intervals, data.frame(patient_id = "PRIVATE-P1"), temporary = TRUE)
  on.exit(DBI::dbRemoveTable(connection, intervals), add = TRUE)
  sources <- getDefaultSnapshotPseudonymizationRuleSources(testthat::test_path("../../../.."))
  rules <- loadPseudonymizationRules(sources$table_descriptions, sources$snapshot_extensions)
  plan <- getExistingSnapshotMaterializationPlan(connection, rules, schema, "v_", SNAPSHOT_LAST_VERSION_SUFFIX, "fall_fe")
  project <- tempfile("bc_project_")
  review <- newBroadConsentReview(file.path(project, "outputLocal", "broad_consent_snapshot", "test"), as.Date("2026-10-22"), "test")
  on.exit(unlink(project, recursive = TRUE), add = TRUE)
  run <- function() prepareBroadConsentResourceSelection(
    connection, plan, rules, schema, "v_", snapshotQualifiedName(connection, intervals),
    log_steps = FALSE, review = review
  )
  testthat::local_mocked_bindings(DEFAULT_SNAPSHOT_CHUNK_SIZE = 1L)
  error <- tryCatch(run(), error = identity)
  expect_s3_class(error, "error")
  message <- conditionMessage(error)
  expect_false(grepl("PRIVATE|777|Key \\(row_id\\)", message))
  expect_match(message, "conflicting_row_ids=1", fixed = TRUE)
  expect_match(message, "Rows without patient consent=1", fixed = TRUE)
  expect_match(message, "Rows with inconsistent patient reference=1", fixed = TRUE)
  evidence <- file.path(review$directory, "decision_conflicts_fall_fe.csv")
  expect_match(message, evidence, fixed = TRUE)
  rows <- data.table::fread(evidence)
  expect_equal(nrow(rows), 3L)
  expect_true(all(rows$row_id == 777L))
  expect_setequal(rows$patient_id, c("PRIVATE-P1", "PRIVATE-P2"))
  expect_setequal(rows$source_input_processing_nr, 101:103)
  expect_true("source_input_datetime" %in% names(rows))
  expect_equal(rows$reason[rows$source_fall_pat_id == "PRIVATE-WRONG"], "patient_not_permitted")
  expect_true(rows$patient_has_consent[rows$source_fall_pat_id == "PRIVATE-WRONG"])
  expect_false(rows$patient_reference_consistent[rows$source_fall_pat_id == "PRIVATE-WRONG"])
  expect_false(dir.exists(file.path(project, "outputGlobal")))
  expect_false(any(grepl("incomplete", list.files(review$directory))))
  expect_equal(nrow(DBI::dbReadTable(connection, DBI::Id(schema = schema, table = "fall_fe"))), 3L)
  expect_equal(as.integer(file.info(evidence)$mode), 384L)
  unlink(evidence)
  testthat::local_mocked_bindings(appendBroadConsentReviewTable = function(...) stop("PRIVATE-WRITE-ERROR"))
  failed <- tryCatch(run(), error = identity)
  expect_match(conditionMessage(failed), "Could not create unique Broad Consent decision index", fixed = TRUE)
  expect_match(conditionMessage(failed), "Local conflict evidence could not be completed", fixed = TRUE)
  expect_false(grepl("PRIVATE", conditionMessage(failed)))
  expect_false(any(grepl("decision_conflicts", list.files(review$directory))))
})

test_that("snapshot failure evidence stays local even with a global report destination", {
  source <- getOption("interpolar.test.postgres_connection")
  target <- getOption("interpolar.test.postgres_target_connection")
  skip_if(is.null(source) || is.null(target), "Two isolated PostgreSQL test connections were not supplied.")
  source_schema <- basename(tempfile("bc_conflict_source_"))
  target_schema <- basename(tempfile("bc_conflict_target_"))
  for (schema in c(source_schema, target_schema)) snapshotEnsureSchema(source, schema)
  on.exit(DBI::dbExecute(source, paste0("DROP SCHEMA ", DBI::dbQuoteIdentifier(source, source_schema), " CASCADE")), add = TRUE)
  on.exit(DBI::dbExecute(target, paste0("DROP SCHEMA ", DBI::dbQuoteIdentifier(target, target_schema), " CASCADE")), add = TRUE)
  tables <- writeBroadConsentSnapshotFixture(source, source_schema)
  DBI::dbExecute(source, paste0("UPDATE ", source_schema, ".fall_fe SET fall_fe_id = 1"))
  rule_sources <- getDefaultSnapshotPseudonymizationRuleSources(testthat::test_path("../../../.."))
  testthat::local_mocked_bindings(getDefaultSnapshotPseudonymizationRuleSources = function(project_root) rule_sources)
  project <- tempfile("bc_project_")
  dir.create(file.path(project, "outputGlobal"), recursive = TRUE)
  on.exit(unlink(project, recursive = TRUE), add = TRUE)
  error <- tryCatch(createBroadConsentSnapshotDatabase(source, target,
    project_root = project, source_schema = source_schema,
    target_table_schema = target_schema, target_view_schema = target_schema,
    tables = names(tables), consent_details = FALSE, evaluation_date = as.Date("2026-09-11"),
    report_file = file.path(project, "outputGlobal", "report.xlsx"), log_steps = FALSE
  ), error = identity)
  expect_match(conditionMessage(error), "Local conflict evidence:", fixed = TRUE)
  files <- list.files(file.path(project, "outputLocal"), pattern = "decision_conflicts_fall_fe.csv", recursive = TRUE, full.names = TRUE)
  expect_length(files, 1L)
  expect_equal(nrow(data.table::fread(files)), 2L)
  expect_length(list.files(file.path(project, "outputGlobal"), recursive = TRUE), 0L)
  expect_equal(DBI::dbGetQuery(target, paste0(
    "SELECT COUNT(*) AS n FROM information_schema.tables WHERE table_schema = ",
    DBI::dbQuoteString(target, target_schema)
  ))$n, 0)
})
